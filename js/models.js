/**
 * Game 3: Heavy Sumo Gyro-Mech
 * Inner metallic sphere, 8 segmented hydraulic ramming shield plates,
 * upper glass cockpit dome with pilot helmet, and rotating neon gyro ring.
 */
export function createSumoMech(colorHex = 0xffb800, radius = 1.15) {
    const group = new THREE.Group();

    const coreMat = new THREE.MeshPhysicalMaterial({
        color: colorHex,
        metalness: 0.85,
        roughness: 0.16,
        clearcoat: 1.0
    });

    const darkMetal = new THREE.MeshStandardMaterial({
        color: 0x1a202c,
        roughness: 0.35,
        metalness: 0.85
    });

    const glowMat = new THREE.MeshStandardMaterial({
        color: colorHex,
        emissive: colorHex,
        emissiveIntensity: 1.5
    });

    // Core armored sphere
    const core = new THREE.Mesh(new THREE.SphereGeometry(radius * 0.92, 28, 28), coreMat);
    core.castShadow = true;
    group.add(core);

    // Equatorial heavy bumper torus + 8 segmented ramming plates
    const bumper = new THREE.Mesh(
        new THREE.TorusGeometry(radius * 0.98, 0.15, 14, 32),
        glowMat
    );
    bumper.rotation.x = Math.PI / 2;
    group.add(bumper);

    for (let i = 0; i < 8; i++) {
        const ang = (i / 8) * Math.PI * 2;
        const plate = new THREE.Mesh(new THREE.BoxGeometry(0.48, 0.52, 0.18), darkMetal);
        plate.position.set(Math.cos(ang) * radius, 0, Math.sin(ang) * radius);
        plate.rotation.y = -ang + Math.PI / 2;
        group.add(plate);
    }

    // Top Glass Cockpit Dome
    const dome = new THREE.Mesh(
        new THREE.SphereGeometry(radius * 0.52, 20, 14, 0, Math.PI * 2, 0, Math.PI * 0.55),
        new THREE.MeshPhysicalMaterial({
            color: 0x88e8ff,
            transmission: 0.7,
            transparent: true,
            opacity: 0.75,
            roughness: 0.08,
            clearcoat: 1.0
        })
    );
    dome.position.y = radius * 0.62;
    group.add(dome);

    return group;
}

