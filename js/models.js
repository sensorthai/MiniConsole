import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';

const gltfLoader = new GLTFLoader();
const modelCache = new Map();

/**
 * Loads a GLTF/GLB 3D model generated by Blender
 * @param {string} url - Path to .glb file in /models/
 * @returns {Promise<THREE.Group>}
 */
export async function loadBlenderModel(url) {
    if (modelCache.has(url)) {
        return modelCache.get(url).clone(true);
    }
    return new Promise((resolve, reject) => {
        gltfLoader.load(
            url,
            (gltf) => {
                const model = gltf.scene;
                model.traverse((child) => {
                    if (child.isMesh) {
                        child.castShadow = true;
                        child.receiveShadow = true;
                    }
                });
                modelCache.set(url, model);
                resolve(model.clone(true));
            },
            undefined,
            (err) => reject(err)
        );
    });
}

const textureCache = new Map();

/**
 * Generates a high-resolution procedural soccer ball texture (hex/pentagon panels + neon seams)
 */
export function getSoccerBallTexture() {
    if (textureCache.has('soccerBall')) return textureCache.get('soccerBall');

    const canvas = document.createElement('canvas');
    canvas.width = 1024;
    canvas.height = 512;
    const ctx = canvas.getContext('2d');

    // Metallic pearl base
    const grad = ctx.createLinearGradient(0, 0, 0, 512);
    grad.addColorStop(0, '#e8f1ff');
    grad.addColorStop(0.5, '#ffffff');
    grad.addColorStop(1, '#cddbef');
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, 1024, 512);

    // Draw hexagonal panel grid across equirectangular map
    const drawPolygon = (cx, cy, r, sides, fill, stroke, lineWidth = 6) => {
        ctx.beginPath();
        for (let i = 0; i < sides; i++) {
            const a = (i / sides) * Math.PI * 2 - Math.PI / 2;
            const x = cx + Math.cos(a) * r;
            const y = cy + Math.sin(a) * r;
            if (i === 0) ctx.moveTo(x, y);
            else ctx.lineTo(x, y);
        }
        ctx.closePath();
        if (fill) {
            ctx.fillStyle = fill;
            ctx.fill();
        }
        if (stroke) {
            ctx.strokeStyle = stroke;
            ctx.lineWidth = lineWidth;
            ctx.stroke();
        }
    };

    const r = 46;
    const dx = r * 1.75;
    const dy = r * 1.52;
    for (let row = -1; row < 9; row++) {
        for (let col = -1; col < 15; col++) {
            const cx = col * dx + (row % 2 === 0 ? 0 : dx * 0.5);
            const cy = row * dy;
            const isDarkPentagon = (row + col) % 3 === 0;
            drawPolygon(
                cx,
                cy,
                r * 0.92,
                6,
                isDarkPentagon ? '#101829' : '#f4f8ff',
                '#00f0ff',
                5
            );
            if (isDarkPentagon) {
                drawPolygon(cx, cy, r * 0.55, 5, '#1d2b47', '#05ffa1', 3);
            }
        }
    }

    // Equatorial tech bands
    ctx.strokeStyle = '#05ffa1';
    ctx.lineWidth = 8;
    ctx.beginPath();
    ctx.moveTo(0, 256);
    ctx.lineTo(1024, 256);
    ctx.stroke();

    const tex = new THREE.CanvasTexture(canvas);
    tex.wrapS = THREE.RepeatWrapping;
    tex.wrapT = THREE.ClampToEdgeWrapping;
    tex.colorSpace = THREE.SRGBColorSpace;
    textureCache.set('soccerBall', tex);
    return tex;
}

/**
 * Builds a single high-detail wheel with rubber tire tread, metallic rim, 5 spokes, and glowing brake disc
 */
export function createDetailedWheel(radius = 0.4, width = 0.34, accentHex = 0x00f0ff) {
    const wheelGroup = new THREE.Group();

    // Outer rubber tire (Cylinder + bevelled Torus sidewalls for realistic rounded tire profile)
    const tireMat = new THREE.MeshStandardMaterial({
        color: 0x15171c,
        roughness: 0.85,
        metalness: 0.15
    });
    const tread = new THREE.Mesh(new THREE.CylinderGeometry(radius, radius, width * 0.82, 24), tireMat);
    tread.rotation.z = Math.PI / 2;
    tread.castShadow = true;
    wheelGroup.add(tread);

    const sidewallGeo = new THREE.TorusGeometry(radius * 0.86, width * 0.22, 12, 24);
    sidewallGeo.rotateY(Math.PI / 2);
    const sideL = new THREE.Mesh(sidewallGeo, tireMat);
    sideL.position.x = -width * 0.28;
    const sideR = new THREE.Mesh(sidewallGeo, tireMat);
    sideR.position.x = width * 0.28;
    wheelGroup.add(sideL, sideR);

    // Metallic alloy rim barrel
    const rimMat = new THREE.MeshStandardMaterial({
        color: 0xd8e2ef,
        roughness: 0.2,
        metalness: 0.92
    });
    const rimBarrel = new THREE.Mesh(
        new THREE.CylinderGeometry(radius * 0.64, radius * 0.64, width * 0.86, 20),
        rimMat
    );
    rimBarrel.rotation.z = Math.PI / 2;
    wheelGroup.add(rimBarrel);

    // 5 Alloy Spokes
    const spokeGeo = new THREE.BoxGeometry(width * 0.88, radius * 1.18, radius * 0.14);
    for (let i = 0; i < 5; i++) {
        const spoke = new THREE.Mesh(spokeGeo, rimMat);
        spoke.rotation.x = (i / 5) * Math.PI;
        wheelGroup.add(spoke);
    }

    // Glowing neon rim lip ring + center lock nut
    const glowMat = new THREE.MeshStandardMaterial({
        color: accentHex,
        emissive: accentHex,
        emissiveIntensity: 1.3,
        roughness: 0.2
    });
    const rimRing = new THREE.Mesh(
        new THREE.TorusGeometry(radius * 0.65, 0.028, 10, 24),
        glowMat
    );
    rimRing.rotation.y = Math.PI / 2;
    rimRing.position.x = width * 0.42;
    const rimRingInner = rimRing.clone();
    rimRingInner.position.x = -width * 0.42;
    wheelGroup.add(rimRing, rimRingInner);

    const centerCap = new THREE.Mesh(
        new THREE.CylinderGeometry(radius * 0.2, radius * 0.2, width * 0.94, 12),
        glowMat
    );
    centerCap.rotation.z = Math.PI / 2;
    wheelGroup.add(centerCap);

    return wheelGroup;
}

