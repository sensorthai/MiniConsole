/**
 * Detailed Mystery Item Box (Octahedron Crystal + Glass Cube + Blender GLB Core)
 */
export function createDetailedItemBox(gameType = 'kart') {
    const group = new THREE.Group();

    const innerCrystal = new THREE.Mesh(
        new THREE.OctahedronGeometry(0.55, 0),
        new THREE.MeshStandardMaterial({
            color: 0xffb800,
            emissive: 0xff6600,
            emissiveIntensity: 1.5,
            roughness: 0.1,
            metalness: 0.9
        })
    );
    group.add(innerCrystal);

    const glassCube = new THREE.Mesh(
        new THREE.BoxGeometry(1.15, 1.15, 1.15),
        new THREE.MeshPhysicalMaterial({
            color: 0x00f0ff,
            transmission: 0.72,
            transparent: true,
            opacity: 0.55,
            roughness: 0.08,
            clearcoat: 1.0
        })
    );
    group.add(glassCube);

    const wireFrame = new THREE.Mesh(
        new THREE.BoxGeometry(1.18, 1.18, 1.18),
        new THREE.MeshBasicMaterial({ color: 0xffb800, wireframe: true })
    );
    group.add(wireFrame);

    const modelMap = {
        kart: '/models/item_kart.glb',
        blaster: '/models/item_blaster.glb',
        sumo: '/models/item_sumo.glb',
        soccer: '/models/item_soccer.glb',
        zombie: '/models/item_zombie.glb'
    };
    const glbUrl = modelMap[gameType] || modelMap.kart;
    loadBlenderModel(glbUrl).then((blenderItem) => {
        blenderItem.scale.setScalar(0.75);
        innerCrystal.visible = false;
        group.add(blenderItem);
        group.userData.innerCrystal = blenderItem;
    }).catch(() => {});

    group.userData = { innerCrystal, glassCube };
    return group;
}

